import 'server-only';
import { mkdir, readFile, rename, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { AwsClient } from 'aws4fetch';
import { getEnv } from '../config/env';

// Documents are files with their hash, outside the structured tables (prompt,
// «الاختيارات التقنية»). The store is an internal interface with two
// implementations: the S3-compatible bucket of the deployment (private, never
// exposed: a document only leaves through the application after its reader's
// rights are checked), and a local directory for development and tests. Keys
// are generated by the platform, never chosen by a depositor.

export interface DocumentStore {
  readonly kind: 's3' | 'disk' | 'memory';
  put(key: string, bytes: Uint8Array, mediaType: string): Promise<void>;
  /** null when no object has this key */
  get(key: string): Promise<Uint8Array | null>;
}

export class DocumentStoreError extends Error {
  constructor(readonly operation: 'put' | 'get', readonly status: number | null) {
    super(`document store ${operation} failed${status === null ? '' : ` (${String(status)})`}`);
    this.name = 'DocumentStoreError';
  }
}

const KEY = /^[a-z0-9/-]{8,200}$/;
function checkKey(key: string): void {
  if (!KEY.test(key) || key.includes('..') || key.startsWith('/')) throw new Error('invalid document key');
}

function s3Store(config: NonNullable<ReturnType<typeof getEnv>['s3']>): DocumentStore {
  const client = new AwsClient({
    accessKeyId: config.accessKeyId,
    secretAccessKey: config.secretAccessKey,
    region: config.region,
    service: 's3',
  });
  const base = new URL(config.endpoint);
  // Virtual-hosted style: https://<bucket>.<endpoint host>/<key>
  const urlOf = (key: string) => `${base.protocol}//${config.bucket}.${base.host}/${key}`;
  return {
    kind: 's3',
    async put(key, bytes, mediaType) {
      checkKey(key);
      const res = await client.fetch(urlOf(key), {
        method: 'PUT',
        body: Buffer.from(bytes),
        headers: { 'content-type': mediaType, 'content-length': String(bytes.byteLength) },
      });
      if (!res.ok) throw new DocumentStoreError('put', res.status);
    },
    async get(key) {
      checkKey(key);
      const res = await client.fetch(urlOf(key), { method: 'GET' });
      if (res.status === 404) return null;
      if (!res.ok) throw new DocumentStoreError('get', res.status);
      return new Uint8Array(await res.arrayBuffer());
    },
  };
}

function diskStore(directory: string): DocumentStore {
  const root = resolve(directory);
  const pathOf = (key: string) => {
    checkKey(key);
    const path = resolve(join(root, key));
    if (!path.startsWith(`${root}/`)) throw new Error('invalid document key');
    return path;
  };
  return {
    kind: 'disk',
    async put(key, bytes) {
      const path = pathOf(key);
      await mkdir(dirname(path), { recursive: true });
      // Written then renamed, so that a reader never sees half a document.
      await writeFile(`${path}.part`, bytes);
      await rename(`${path}.part`, path);
    },
    async get(key) {
      try {
        return new Uint8Array(await readFile(pathOf(key)));
      } catch (error) {
        if ((error as NodeJS.ErrnoException).code === 'ENOENT') return null;
        throw new DocumentStoreError('get', null);
      }
    },
  };
}

let store: DocumentStore | null = null;

/** The store chosen by configuration; the boot check refuses production without the bucket. */
export function documentStore(): DocumentStore {
  if (store) return store;
  const env = getEnv();
  if (env.s3) store = s3Store(env.s3);
  else if (env.documentStoreDir) store = diskStore(env.documentStoreDir);
  else throw new Error('no document store configured (S3_* or DOCUMENT_STORE_DIR)');
  return store;
}

export function documentStoreConfigured(): 's3' | 'disk' | null {
  const env = getEnv();
  return env.s3 ? 's3' : env.documentStoreDir ? 'disk' : null;
}

export function setDocumentStoreForTests(next: DocumentStore | null): void {
  store = next;
}
